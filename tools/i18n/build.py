"""Builds src/i18n/locales/<lang>.ts from the numbered translation files.

tools/i18n/strings.json            English strings (keys), from extract.py
tools/i18n/numbered.txt            the same list, numbered: "<n>|<English>" (what translators work from)
tools/i18n/<lang>/*.txt            translations: "<n>|<translation>", one per line, \\n for a line break

Checks every translation: the number exists, {placeholders} are the same as in English, nothing is
empty. Missing lines fall back to English in the app (and are listed here).

  python3 tools/i18n/build.py number   # (re)writes numbered.txt from strings.json
  python3 tools/i18n/build.py          # builds the locale files and reports coverage
"""
import glob, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
LANGS = ['hi', 'es', 'fr', 'de', 'ur', 'ar', 'pa', 'ru', 'pt']
NAMES = {'hi': 'Hindi', 'es': 'Spanish', 'fr': 'French', 'de': 'German', 'ur': 'Urdu', 'ar': 'Arabic', 'pa': 'Punjabi', 'ru': 'Russian', 'pt': 'Portuguese'}
PH = re.compile(r'\{(\w+)\}')


def english():
    return list(json.load(open(os.path.join(HERE, 'strings.json'), encoding='utf-8')).keys())


def number():
    """Keeps the numbers of strings already numbered; new strings get new numbers at the end."""
    path = os.path.join(HERE, 'numbered.txt')
    old = {}
    if os.path.exists(path):
        for line in open(path, encoding='utf-8'):
            n, _, en = line.rstrip('\n').partition('|')
            old[en.replace('\\n', '\n')] = int(n)
    nxt = max(old.values(), default=0) + 1
    rows = []
    for en in english():
        if en not in old:
            old[en] = nxt
            nxt += 1
        rows.append((old[en], en))
    rows.sort()
    with open(path, 'w', encoding='utf-8') as f:
        for n, en in rows:
            f.write(f"{n}|{en.replace(chr(10), chr(92) + 'n')}\n")
    print(len(rows), 'strings numbered ->', path)


def build():
    num = {}
    for line in open(os.path.join(HERE, 'numbered.txt'), encoding='utf-8'):
        n, _, en = line.rstrip('\n').partition('|')
        num[int(n)] = en.replace('\\n', '\n')
    live = set(english())
    report = []
    for lang in LANGS:
        tr = {}
        bad = []
        for fpath in sorted(glob.glob(os.path.join(HERE, lang, '*.txt'))):
            for i, line in enumerate(open(fpath, encoding='utf-8'), 1):
                line = line.rstrip('\n')
                if not line.strip():
                    continue
                n, sep, t = line.partition('|')
                if not sep or not n.strip().isdigit():
                    bad.append(f'{os.path.basename(fpath)}:{i}: no number')
                    continue
                n = int(n)
                if n not in num:
                    bad.append(f'{os.path.basename(fpath)}:{i}: unknown number {n}')
                    continue
                t = t.strip().replace('\\n', '\n')
                en = num[n]
                if not t:
                    bad.append(f'{n}: empty')
                    continue
                if sorted(PH.findall(en)) != sorted(PH.findall(t)):
                    bad.append(f'{n}: placeholders differ: {en!r} -> {t!r}')
                    continue
                tr[en] = t
        keys = [en for en in tr if en in live]
        missing = [en for en in live if en not in tr]
        out = os.path.join(ROOT, 'src', 'i18n', 'locales', f'{lang}.ts')
        with open(out, 'w', encoding='utf-8') as f:
            f.write(f'/* {NAMES[lang]} translations (keys = English text). Generated by tools/i18n/build.py — edit tools/i18n/{lang}/*.txt instead. */\n')
            f.write('const d: Record<string, string> = ' + json.dumps({k: tr[k] for k in sorted(keys)}, ensure_ascii=False, indent=1) + ';\nexport default d;\n')
        report.append((lang, len(keys), len(live), missing, bad))
    for lang, have, total, missing, bad in report:
        print(f'{lang}: {have}/{total} translated' + (f', {len(bad)} problems' if bad else ''))
        for b in bad[:20]:
            print('   ', b)
        if missing and '-v' in sys.argv:
            for m in missing[:30]:
                print('    missing:', m[:80])
    return report


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'number':
        number()
    else:
        build()
